----------------------------------------------------------------------------------------------------------------------------------------
-- LIBRARIES
----------------------------------------------------------------------------------------------------------------------------------------

-- IEEE Standard Library
library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

-- IEEE Numeric Standard Library
use IEEE.NUMERIC_STD.ALL;


----------------------------------------------------------------------------------------------------------------------------------------
-- ENTITY
----------------------------------------------------------------------------------------------------------------------------------------
entity branch_cmp is
port(
    i_data_A                    : in 	std_logic_vector(31 downto 0);                      -- Register A Data
    i_data_B                    : in	std_logic_vector(31 downto 0);                      -- Register B Data

	i_BrU			            : in 	std_logic;						                    -- Unsigned/Signed Switch
    o_BrEQ			            : out	std_logic;						                    -- Branch When Equal
    o_BrLT			            : out	std_logic						                    -- Branch When Lesser Than

);
end entity;


----------------------------------------------------------------------------------------------------------------------------------------
-- ARCHITECTURE
----------------------------------------------------------------------------------------------------------------------------------------
architecture branch_cmp_arch of branch_cmp is


	------------------------------------------------------------------------------------------------------------------------------------
	-- SIGNAL DECLARATIONS
	------------------------------------------------------------------------------------------------------------------------------------

        -- n/a


begin

	------------------------------------------------------------------------------------------------------------------------------------
	-- SIGNAL ASSIGNMENTS
	------------------------------------------------------------------------------------------------------------------------------------

    -- Determine Branch When Equal signal
    o_BrEQ          <=  '1'     when (unsigned( i_data_A ) = unsigned( i_data_B ))  and i_BrU = '1'    else
                        '1'     when (signed( i_data_A ) = signed( i_data_B ))      and i_BrU = '0'    else
                        '0';


    -- Determine Branch When Lesser Than
    o_BrLT          <=  '1'     when (unsigned( i_data_A ) < unsigned( i_data_B ))  and i_BrU = '1'    else
                        '1'     when (signed( i_data_A ) < signed( i_data_B ))      and i_BrU = '0'    else
                        '0';
	

end architecture;
